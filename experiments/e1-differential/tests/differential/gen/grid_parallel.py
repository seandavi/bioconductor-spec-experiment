"""Generate cases/grid_parallel.yaml: p* ops over every pair from a small range pool.

    uv run python tests/differential/gen/grid_parallel.py

One case per op covers hundreds of pairs, so edge cases (empty ranges, adjacency,
containment) are hit exhaustively. Pair filters only avoid pairs R is documented to
reject; the "-error" cases cover those separately.
"""

from __future__ import annotations

import itertools
from pathlib import Path

import yaml

POOL = [(s, w) for s in range(1, 6) for w in range(0, 4)]
PAIRS = list(itertools.product(POOL, POOL))


def ir(pairs: list[tuple[int, int]]) -> dict:
    return {"IRanges": {"start": [s for s, _ in pairs], "width": [w for _, w in pairs]}}


def case(cid: str, fn: str, pairs: list, kwargs: dict | None = None) -> dict:
    out: dict = {
        "id": cid,
        "tags": ["grid", fn],
        "inputs": {"x": ir([a for a, _ in pairs]), "y": ir([b for _, b in pairs])},
        "call": {"fn": fn, "args": ["$x", "$y"]},
    }
    if kwargs:
        out["call"]["kwargs"] = kwargs
    return out


def end(s: int, w: int) -> int:
    return s + w - 1


def gap(a: tuple[int, int], b: tuple[int, int]) -> int:
    return max(a[0], b[0]) - min(end(*a), end(*b)) - 1


no_gap = [p for p in PAIRS if gap(*p) <= 0]
has_gap = [p for p in PAIRS if gap(*p) > 0]
unambiguous = [p for p in PAIRS if gap(*p) <= 0]
ambiguous = [p for p in PAIRS if gap(*p) > 0]
sub_ok = [p for p in PAIRS if not (p[1][0] > p[0][0] and end(*p[1]) < end(*p[0]))]
sub_bad = [p for p in PAIRS if p[1][0] > p[0][0] and end(*p[1]) < end(*p[0])]

cases = [
    case("grid-punion-fill-gap", "punion", PAIRS, {"fill.gap": True}),
    case("grid-punion-no-gap-pairs", "punion", no_gap),
    case("grid-punion-gap-pairs-error", "punion", has_gap[:1]),
    case("grid-pintersect-none", "pintersect", unambiguous),
    case("grid-pintersect-ambiguous-error", "pintersect", ambiguous[:1]),
    case("grid-pintersect-max-start", "pintersect", PAIRS, {"resolve.empty": "max.start"}),
    case("grid-pintersect-start-x", "pintersect", PAIRS, {"resolve.empty": "start.x"}),
    case("grid-psetdiff", "psetdiff", sub_ok),
    case("grid-psetdiff-split-error", "psetdiff", sub_bad[:1]),
]

out = Path(__file__).parent.parent / "cases" / "grid_parallel.yaml"
out.write_text("# GENERATED by gen/grid_parallel.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
