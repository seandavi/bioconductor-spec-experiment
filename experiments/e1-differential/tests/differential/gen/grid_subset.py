"""Generate cases/grid_subset.yaml: `[` with every kind of subscript on IRanges / GRanges (named, dup names, mcols).

    uv run python tests/differential/gen/grid_subset.py
"""

from __future__ import annotations

from pathlib import Path

import yaml

X = {"IRanges": {"start": [1, 5, 9, 12], "width": [2, 0, 3, 1], "names": ["a", "b", "a", "d"], "mcols": {"m": [1, 2, 3, 4]}}}
XU = {"IRanges": {"start": [1, 5, 9, 12], "width": [2, 0, 3, 1], "mcols": {"m": [1, 2, 3, 4]}}}
G = {"GRanges": {"seqnames": ["c1", "c2", "c1", "c2"], "start": [1, 5, 9, 12], "width": [2, 0, 3, 1], "strand": ["+", "-", "*", "+"],
                 "names": ["a", "b", "a", "d"], "mcols": {"m": [1, 2, 3, 4]}, "seqinfo": {"seqnames": ["c1", "c2", "c3"], "seqlengths": [50, 50, 50]}}}
SUBS: dict[str, object] = {
    "int": [3, 1], "rep": [2, 2, 2], "neg": [-1], "negs": [-1, -3], "zero": [0], "zero-int": [0, 2], "mixed": [-1, 2], "mixed-zero": [-1, 0],
    "na": [None], "int-na": [1, None], "oob": [5], "neg-oob": [-5], "neg-oob-mixed": [-1, -5], "dbl": {"num": [1.9, 2.1]}, "dbl-neg": {"num": [-1.5]},
    "lgl": [True, False, True, False], "lgl-short": [True, False], "lgl-one": [True], "lgl-false": [False], "lgl-long": [True, False, True, False, False],
    "lgl-long-true": [True, False, True, False, True], "lgl-na": [True, None, False, False], "empty": {"int": []}, "empty-lgl": {"lgl": []}, "empty-chr": {"chr": []},
    "name": ["d"], "name-dup": ["a"], "name-missing": ["zz"], "names": ["d", "a", "b"], "name-na": [None], "chr-empty-string": [""],
    "all": [1, 2, 3, 4], "rev": [4, 3, 2, 1],
}
cases: list[dict] = []
for kind, obj in (("irn", X), ("iru", XU), ("grn", G)):
    for sname, sub in SUBS.items():
        cases.append({"id": f"subset-{kind}-{sname}", "tags": ["subset"], "inputs": {"x": obj}, "call": {"fn": "[", "args": ["$x", sub]}})
    cases.append({"id": f"subset-{kind}-empty-object-int", "tags": ["subset", "empty"],
                  "inputs": {"x": {("IRanges" if kind != "grn" else "GRanges"): {k: v for k, v in (obj.get("IRanges") or obj.get("GRanges")).items() if k in ("seqinfo",)} | ({"start": {"int": []}, "width": {"int": []}} | ({"seqnames": {"chr": []}} if kind == "grn" else {}))}},
                  "call": {"fn": "[", "args": ["$x", [1]]}})

out = Path(__file__).parent.parent / "cases" / "grid_subset.yaml"
out.write_text("# GENERATED by gen/grid_subset.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
