"""Generate cases/grid_mcols_types.yaml: mcols column-type combinations through c() and subsetting.

    uv run python tests/differential/gen/grid_mcols_types.py
"""

from __future__ import annotations

import itertools
from pathlib import Path

import yaml

COLS: dict[str, list] = {
    "int": [1, 2], "dbl": {"num": [1.5, 2.5]}, "chr": ["a", "b"], "lgl": [True, False], "na-int": [1, None], "na-chr": ["a", None],
    "na-lgl": [True, None], "na-dbl": {"num": [1.5, None]}, "dbl-whole": {"num": [2, 30]}, "dbl-long": {"num": [0.1, 1234567.123456789]},
}
cases: list[dict] = []
for (a, av), (b, bv) in itertools.product(COLS.items(), COLS.items()):
    for kind in ("ir", "gr"):
        if kind == "ir":
            x = {"IRanges": {"start": [1, 2], "width": [3, 3], "mcols": {"m": av}}}
            y = {"IRanges": {"start": [5, 6], "width": [1, 1], "mcols": {"m": bv}}}
        else:
            x = {"GRanges": {"seqnames": ["c", "c"], "start": [1, 2], "width": [3, 3], "mcols": {"m": av}}}
            y = {"GRanges": {"seqnames": ["c", "c"], "start": [5, 6], "width": [1, 1], "mcols": {"m": bv}}}
        cases.append({"id": f"mcols-{kind}-concat-{a}-{b}", "tags": ["mcols", "concat"], "inputs": {"x": x, "y": y},
                      "call": {"fn": "c", "args": ["$x", "$y"]}})
for a, av in COLS.items():
    x = {"IRanges": {"start": [1, 2], "width": [3, 3], "mcols": {"m": av}}}
    cases.append({"id": f"mcols-ir-roundtrip-{a}", "tags": ["mcols"], "inputs": {"x": x}, "call": {"fn": "identity", "args": ["$x"]}})
    cases.append({"id": f"mcols-ir-subset-{a}", "tags": ["mcols"], "inputs": {"x": x}, "call": {"fn": "[", "args": ["$x", [2, 1, 1]]}})
    cases.append({"id": f"mcols-ir-getter-{a}", "tags": ["mcols"], "inputs": {"x": x}, "call": {"fn": "mcols", "args": ["$x"]}})
    cases.append({"id": f"mcols-ir-empty-subset-{a}", "tags": ["mcols", "empty"], "inputs": {"x": x}, "call": {"fn": "[", "args": ["$x", {"int": []}]}})
    cases.append({"id": f"mcols-ir-concat-empty-{a}", "tags": ["mcols", "empty"],
                  "inputs": {"x": x, "e": {"IRanges": {"start": {"int": []}, "width": {"int": []}}}}, "call": {"fn": "c", "args": ["$e", "$x"]}})
cases.append({"id": "mcols-two-columns-order", "tags": ["mcols", "concat"],
              "inputs": {"x": {"IRanges": {"start": [1], "width": [1], "mcols": {"b": [1], "a": [2]}}}, "y": {"IRanges": {"start": [2], "width": [1], "mcols": {"a": [3], "c": [4]}}}},
              "call": {"fn": "c", "args": ["$x", "$y"]}})
cases.append({"id": "mcols-column-named-hit-and-revmap", "tags": ["mcols", "quirk"],
              "inputs": {"x": {"IRanges": {"start": [1, 2], "width": [3, 3], "mcols": {"revmap": [9, 8], "hit": [True, False]}}}},
              "call": {"fn": "[", "args": ["$x", [2]]}})

out = Path(__file__).parent.parent / "cases" / "grid_mcols_types.yaml"
out.write_text("# GENERATED by gen/grid_mcols_types.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
