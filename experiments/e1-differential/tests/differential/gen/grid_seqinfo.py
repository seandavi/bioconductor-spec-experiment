"""Generate cases/grid_seqinfo.yaml: random seqinfo pairs (level subsets/permutations, conflicting or missing
lengths / circularity / genome) through every two-object GRanges operation, with warnings compared.

    uv run python tests/differential/gen/grid_seqinfo.py
"""

from __future__ import annotations

import random
from pathlib import Path

import yaml

rng = random.Random(99)
LEVELS = ["chr1", "chr2", "chr3", "chrX"]


def seqinfo() -> dict:
    lv = rng.sample(LEVELS, rng.randint(1, 4))
    d: dict = {"seqnames": lv}
    if rng.random() < 0.7:
        d["seqlengths"] = [rng.choice([None, 100, 100, 50]) for _ in lv]
    if rng.random() < 0.4:
        d["is_circular"] = [rng.choice([None, True, False]) for _ in lv]
    if rng.random() < 0.4:
        d["genome"] = [rng.choice([None, "hg19", "hg19", "hg38"]) for _ in lv]
    return d


def gr(si: dict, n: int = 4) -> dict:
    return {"GRanges": {"seqnames": [rng.choice(si["seqnames"]) for _ in range(n)], "start": [rng.randint(1, 40) for _ in range(n)],
                        "width": [rng.choice([0, 3, 8]) for _ in range(n)], "strand": [rng.choice(["+", "-", "*"]) for _ in range(n)], "seqinfo": si}}


cases: list[dict] = []
for k in range(40):
    sa, sb = seqinfo(), seqinfo()
    x, y = gr(sa), gr(sb)
    inputs = {"x": x, "y": y}
    for fn in ("c", "union", "intersect", "setdiff", "findOverlaps", "punion", "pintersect", "psetdiff", "range", "nearest", "precede", "follow", "distance", "countOverlaps"):
        kw: dict = {"select": "arbitrary"} if fn == "nearest" else {}
        cases.append({"id": f"si{k}-{fn}", "tags": ["seqinfo", fn, "warning"], "check_warnings": True, "inputs": inputs,
                      "call": {"fn": fn, "args": ["$x", "$y"], **({"kwargs": kw} if kw else {})}})
    cases.append({"id": f"si{k}-c-seqinfo", "tags": ["seqinfo", "c"], "inputs": inputs,
                  "call": {"fn": "seqinfo", "args": [{"call": {"fn": "c", "args": ["$x", "$y"]}}]}})
    cases.append({"id": f"si{k}-c-three", "tags": ["seqinfo", "c", "warning"], "check_warnings": True, "inputs": {**inputs, "z": gr(seqinfo())},
                  "call": {"fn": "seqinfo", "args": [{"call": {"fn": "c", "args": ["$x", "$y", "$z"]}}]}})

out = Path(__file__).parent.parent / "cases" / "grid_seqinfo.yaml"
out.write_text("# GENERATED by gen/grid_seqinfo.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
