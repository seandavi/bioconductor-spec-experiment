"""Generate cases/grid_nearest.yaml: nearest / precede / follow / distance on small pools.

    uv run python tests/differential/gen/grid_nearest.py
"""

from __future__ import annotations

import itertools
from pathlib import Path

import yaml


def ir(pairs: list[tuple[int, int]]) -> dict:
    return {"IRanges": {"start": [s for s, _ in pairs], "width": [w for _, w in pairs]}}


Q = [(s, w) for w in range(0, 4) for s in range(1, 8)]
SUBJECTS = {
    "ties": [(10, 2), (3, 4), (3, 4), (5, 0), (1, 2), (12, 3), (20, 1), (14, 0)],
    "symmetric": [(1, 2), (9, 2), (5, 1), (5, 1)],
    "nested": [(1, 20), (3, 2), (3, 5), (10, 1), (10, 1)],
    "one": [(8, 2)],
}
cases: list[dict] = []
for sname, subj in SUBJECTS.items():
    for qname, q in (("big", Q), ("small", Q[4:24:7])):
        for fn, sels in (("nearest", ("arbitrary", "all")), ("precede", ("first", "all")), ("follow", ("last", "all"))):
            for sel in sels:
                cases.append({
                    "id": f"grid-{fn}-{sel}-{sname}-q{qname}",
                    "tags": ["grid", fn],
                    "inputs": {"q": ir(q), "s": ir(subj)},
                    "call": {"fn": fn, "args": ["$q", "$s"], "kwargs": {"select": sel}},
                })
    for fn in ("nearest", "precede", "follow"):
        cases.append({
            "id": f"grid-{fn}-self-{sname}", "tags": ["grid", fn, "self"],
            "inputs": {"s": ir(subj)}, "call": {"fn": fn, "args": ["$s"]},
        })
        cases.append({
            "id": f"grid-{fn}-self-all-{sname}", "tags": ["grid", fn, "self"],
            "inputs": {"s": ir(subj)}, "call": {"fn": fn, "args": ["$s"], "kwargs": {"select": "all"}},
        })
pairs = list(itertools.product(Q, Q))
cases.append({
    "id": "grid-distance-all-pairs", "tags": ["grid", "distance"],
    "inputs": {"x": ir([a for a, _ in pairs]), "y": ir([b for _, b in pairs])},
    "call": {"fn": "distance", "args": ["$x", "$y"]},
})

out = Path(__file__).parent.parent / "cases" / "grid_nearest.yaml"
out.write_text("# GENERATED by gen/grid_nearest.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
