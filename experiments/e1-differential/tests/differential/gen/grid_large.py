"""Generate cases/grid_large.yaml: a few hundred ranges with deep nesting and many ties.

    uv run python tests/differential/gen/grid_large.py

Larger inputs than the other grids so NCList-order effects (nesting, equal starts, duplicates) show up.
"""

from __future__ import annotations

import random
from pathlib import Path

import yaml

rng = random.Random(424242)
cases: list[dict] = []


def ir(n: int, span: int, widths: list[int]) -> dict:
    return {"IRanges": {"start": [rng.randint(1, span) for _ in range(n)], "width": [rng.choice(widths) for _ in range(n)]}}


def gr(n: int, span: int, widths: list[int]) -> dict:
    return {"GRanges": {"seqnames": [rng.choice(["chr1", "chr2", "chr3"]) for _ in range(n)], "start": [rng.randint(1, span) for _ in range(n)],
                        "width": [rng.choice(widths) for _ in range(n)], "strand": [rng.choice(["+", "-", "*"]) for _ in range(n)],
                        "seqinfo": {"seqnames": ["chr1", "chr2", "chr3"], "seqlengths": [100000, 100000, 100000]}}}


for tag, (nq, ns, span, widths) in {"nested": (150, 150, 200, [0, 1, 5, 20, 60, 150]), "qshort": (40, 300, 400, [0, 2, 9, 40, 200]), "qlong": (300, 60, 300, [0, 3, 30, 100])}.items():
    for kind, mk in (("ir", ir), ("gr", gr)):
        q, s = mk(nq, span, widths), mk(ns, span, widths)
        inputs = {"q": q, "s": s}
        for typ in ("any", "start", "end", "within", "equal"):
            cases.append({"id": f"large-{kind}-{tag}-fo-{typ}", "tags": ["large", "findOverlaps"], "inputs": inputs,
                          "call": {"fn": "findOverlaps", "args": ["$q", "$s"], "kwargs": {"type": typ}}})
        for sel in ("first", "last", "arbitrary"):
            cases.append({"id": f"large-{kind}-{tag}-fo-select-{sel}", "tags": ["large", "findOverlaps"], "inputs": inputs,
                          "call": {"fn": "findOverlaps", "args": ["$q", "$s"], "kwargs": {"select": sel}}})
        cases.append({"id": f"large-{kind}-{tag}-fo-maxgap", "tags": ["large", "findOverlaps"], "inputs": inputs,
                      "call": {"fn": "findOverlaps", "args": ["$q", "$s"], "kwargs": {"type": "within", "maxgap": 7, "minoverlap": 2}}})
        for fn, sel in (("nearest", "arbitrary"), ("nearest", "all"), ("precede", "first"), ("precede", "all"), ("follow", "last"), ("follow", "all")):
            cases.append({"id": f"large-{kind}-{tag}-{fn}-{sel}", "tags": ["large", fn], "inputs": inputs,
                          "call": {"fn": fn, "args": ["$q", "$s"], "kwargs": {"select": sel}}})
        cases.append({"id": f"large-{kind}-{tag}-self", "tags": ["large", "findOverlaps", "self"], "inputs": {"q": q},
                      "call": {"fn": "findOverlaps", "args": ["$q"], "kwargs": {"drop.self": True, "drop.redundant": True}}})
        for fn in ("reduce", "disjoin", "gaps", "range", "coverage", "order", "unique"):
            kw = {"with.revmap": True} if fn in ("reduce", "disjoin") else {}
            cases.append({"id": f"large-{kind}-{tag}-{fn}", "tags": ["large", fn], "inputs": {"q": q}, "call": {"fn": fn, "args": ["$q"], **({"kwargs": kw} if kw else {})}})
        for fn in ("union", "intersect", "setdiff"):
            cases.append({"id": f"large-{kind}-{tag}-{fn}", "tags": ["large", fn], "inputs": inputs, "call": {"fn": fn, "args": ["$q", "$s"]}})

out = Path(__file__).parent.parent / "cases" / "grid_large.yaml"
out.write_text("# GENERATED by gen/grid_large.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
