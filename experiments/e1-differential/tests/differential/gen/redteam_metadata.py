"""Build metadata/validation interaction cases; retain reviewed xfail reasons."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

OUT = Path(__file__).parents[1] / "cases" / "redteam_metadata.yaml"
cases: list[dict[str, Any]] = []


def ranges(kind: str, n: int = 3, **fields: Any) -> dict[str, Any]:
    body: dict[str, Any] = {"start": list(range(1, 2 * n, 2)), "width": [2] * n,
                            "names": [f"r{i}" for i in range(n)]}
    if kind == "GRanges":
        body.update(seqnames=["chr1"], strand=["+"])
    body.update(fields)
    return {kind: body}


def add(cid: str, inputs: dict[str, Any], fn: str, args: list[Any] | None = None,
        **kwargs: Any) -> None:
    cases.append({"id": f"rt-meta-{cid}", "tags": ["redteam", "metadata", fn], "inputs": inputs,
                  "call": {"fn": fn, "args": args if args is not None else ["$x"], "kwargs": kwargs}})


for kind, tag in (("IRanges", "ir"), ("GRanges", "gr")):
    for n, values, suffix in ((3, [7], "scalar"), (4, [7, 8], "divisor"),
                              (3, [7, 8], "nondivisor"), (3, {"int": []}, "zero")):
        add(f"{tag}-construct-mcols-{suffix}", {"x": ranges(kind, n, mcols={"score": values})}, "identity")
        add(f"{tag}-set-mcols-{suffix}", {"x": ranges(kind, n)}, "mcols<-", value={"DataFrame": {"score": values}})
    add(f"{tag}-flank-na-logical", {"x": ranges(kind)}, "flank", ["$x", 2],
        start={"lgl": [True, None, False]})
    add(f"{tag}-coverage-weight-column", {"x": ranges(kind, mcols={"score": [1, 2, 3]})}, "coverage", weight="score")

for name in ("start", "seqnames", "strand", "width"):
    add(f"gr-reserved-{name}", {"x": ranges("GRanges", mcols={name: [1, 2, 3]})}, "identity")
add("gr-nonreserved-control", {"x": ranges("GRanges", mcols={"hit": [False, False, False]})}, "identity")

x = ranges("GRanges", mcols={"hit": [False, False, False], "label": ["a", "b", "c"]})
y = ranges("GRanges", start=[2, 10, 5], width=[2, 2, 2])
for drop in (False, True):
    add(f"gr-pintersect-existing-hit-{'drop' if drop else 'keep'}", {"x": x, "y": y}, "pintersect", ["$x", "$y"],
        **{"drop.nohit.ranges": drop})
add("gr-coverage-shift-column", {"x": ranges("GRanges", mcols={"offset": [0, 1, 2]})}, "coverage", shift="offset")
add("gr-coverage-na-column", {"x": ranges("GRanges", mcols={"score": [1, None, 3]})}, "coverage", weight="score")
add("gr-strand-text-na", {"x": ranges("GRanges", strand=["NA"])}, "identity")
add("gr-strand-numeric", {"x": ranges("GRanges", strand=[1, -1, 0])}, "identity")
add("gr-strand-typed-missing", {"x": ranges("GRanges", strand={"chr": ["+", None, "-"]})}, "identity")

for suffix, si in (
    ("numeric-circular", {"seqnames": ["chr1", "chr2"], "is_circular": [0, 1]}),
    ("text-circular", {"seqnames": ["chr1", "chr2"], "is_circular": ["FALSE", "TRUE"]}),
    ("empty", {"seqnames": {"chr": []}}),
):
    add(f"seqinfo-{suffix}", {"x": {"Seqinfo": si}}, "identity")

cases.append({"id": "rt-meta-seqinfo-numeric-names", "tags": ["redteam", "metadata", "Seqinfo"],
              "raw": {"r": "Seqinfo(c(1L, 2L))", "py": "Seqinfo([1, 2])"}})

# R's seqinfo replacement validates the old-to-new level mapping, even when
# the replacement retains every sequence in use.
x = ranges("GRanges", seqinfo={"seqnames": ["chr1", "chr2"], "seqlengths": [10, 20]})
for suffix, si in (
    ("reorder", {"seqnames": ["chr2", "chr1"], "seqlengths": [20, 10]}),
    ("drop-unused", {"seqnames": ["chr1"], "seqlengths": [10]}),
    ("drop-used", {"seqnames": ["chr2"], "seqlengths": [20]}),
):
    add(f"gr-set-seqinfo-{suffix}", {"x": x}, "seqinfo<-", value={"Seqinfo": si})

# Named IRanges recycled into GRanges: names come from ranges unless replaced.
cases.append({"id": "rt-meta-gr-recycle-range-names", "tags": ["redteam", "metadata", "construct"],
              "raw": {"r": 'GRanges(c("a", "b"), IRanges(1L, width=2L, names="only"))',
                      "py": 'GRanges(["a", "b"], IRanges([1], width=[2], names=["only"]))'}})

old = yaml.safe_load(OUT.read_text()) if OUT.exists() else {}
reasons = {c["id"]: c["xfail"] for c in old.get("cases", []) if "xfail" in c}
for case in cases:
    case["check_warnings"] = True
    if case["id"] in reasons:
        case["xfail"] = reasons[case["id"]]
OUT.write_text("# Generated by gen/redteam_metadata.py; reviewed xfail reasons are retained.\n" +
               yaml.safe_dump({"cases": cases}, sort_keys=False, width=110))
print(f"wrote {len(cases)} cases")
