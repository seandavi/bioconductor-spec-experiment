"""Generate cases/grid_construct.yaml: IRanges / GRanges constructors over odd argument combinations.

    uv run python tests/differential/gen/grid_construct.py
"""

from __future__ import annotations

import itertools
from pathlib import Path

import yaml

V: dict[str, object] = {
    "int3": [1, 5, 9], "int1": [4], "dbl": {"num": [1.5, 2.5, 3.5]}, "dblwhole": {"num": [2, 3, 4]}, "str": ["a", "b", "c"],
    "na": [1, None, 3], "lgl": [True, False, True], "empty": {"int": []}, "int2": [1, 2], "neg": [-2, -1, 0], "width0": [0, 0, 0],
    "negw": [-1, 2, 3], "int4": [1, 2, 3, 4],
}
cases: list[dict] = []
for (a, av), (b, bv) in itertools.product(V.items(), V.items()):
    for pair in (("start", "width"), ("start", "end"), ("end", "width")):
        if (pair[0], pair[1]) != ("start", "width") and (a, b) not in {("int3", "int3"), ("int3", "int1"), ("int1", "int3"), ("dbl", "int3"), ("na", "int3"), ("str", "int3"), ("neg", "int3"), ("int3", "neg"), ("empty", "int3"), ("int3", "width0")}:
            continue
        cases.append({
            "id": f"ctor-ir-{pair[0]}-{a}-{pair[1]}-{b}", "tags": ["construct", "bad-args"],
            "inputs": {"x": {"IRanges": {pair[0]: av, pair[1]: bv}}}, "call": {"fn": "identity", "args": ["$x"]},
        })
for a, av in V.items():
    cases.append({"id": f"ctor-ir-start-only-{a}", "tags": ["construct", "bad-args"], "inputs": {"x": {"IRanges": {"start": av}}},
                  "call": {"fn": "identity", "args": ["$x"]}})
    cases.append({"id": f"ctor-ir-names-{a}", "tags": ["construct", "names"], "inputs": {"x": {"IRanges": {"start": [1, 5, 9], "width": [1, 1, 1], "names": av}}},
                  "call": {"fn": "identity", "args": ["$x"]}})
    cases.append({"id": f"ctor-ir-three-{a}", "tags": ["construct"], "inputs": {"x": {"IRanges": {"start": [1, 5, 9], "end": [2, 5, 11], "width": av}}},
                  "call": {"fn": "identity", "args": ["$x"]}})
SEQ: dict[str, object] = {"one": ["chr1"], "three": ["chr1", "chr2", "chr1"], "two": ["chr1", "chr2"], "num": [1, 2, 3], "na": ["chr1", None, "chr1"], "empty": {"chr": []},
                          "blank": ["", "chr1", "chr2"], "four": ["a", "b", "c", "d"]}
STR: dict[str, object] = {"plus": ["+"], "mixed": ["+", "-", "*"], "two": ["+", "-"], "bad": ["+", "x", "-"], "na": ["+", None, "-"], "dot": [".", ".", "."], "empty": {"chr": []},
                          "num": [1, -1, 0], "four": ["+", "-", "*", "+"]}
for (sn, sv), (stn, stv) in itertools.product(SEQ.items(), STR.items()):
    cases.append({"id": f"ctor-gr-seq-{sn}-strand-{stn}", "tags": ["construct", "bad-args"],
                  "inputs": {"g": {"GRanges": {"seqnames": sv, "start": [1, 5, 9], "width": [2, 2, 2], "strand": stv}}}, "call": {"fn": "identity", "args": ["$g"]}})
for a, av in V.items():
    cases.append({"id": f"ctor-gr-start-{a}", "tags": ["construct", "bad-args"], "inputs": {"g": {"GRanges": {"seqnames": ["chr1"], "start": av, "width": [1, 1, 1]}}},
                  "call": {"fn": "identity", "args": ["$g"]}})
    cases.append({"id": f"ctor-gr-width-{a}", "tags": ["construct", "bad-args"], "inputs": {"g": {"GRanges": {"seqnames": ["chr1", "chr2", "chr1"], "start": [1, 5, 9], "width": av}}},
                  "call": {"fn": "identity", "args": ["$g"]}})
SI: dict[str, object] = {
    "ok": {"seqnames": ["chr1", "chr2"], "seqlengths": [100, 200]},
    "dup": {"seqnames": ["chr1", "chr1"]}, "blank": {"seqnames": ["chr1", ""]}, "negl": {"seqnames": ["chr1", "chr2"], "seqlengths": [-1, 2]},
    "dbll": {"seqnames": ["chr1", "chr2"], "seqlengths": {"num": [10.7, 20.2]}}, "shortl": {"seqnames": ["chr1", "chr2"], "seqlengths": [1]},
    "circ": {"seqnames": ["chr1", "chr2"], "seqlengths": [100, 200], "is_circular": [True, False]}, "circshort": {"seqnames": ["chr1", "chr2"], "is_circular": [True]},
    "genome1": {"seqnames": ["chr1", "chr2"], "genome": ["h"]}, "genome2": {"seqnames": ["chr1", "chr2"], "genome": ["h", "g"]}, "genome3": {"seqnames": ["chr1", "chr2"], "genome": ["a", "b", "c"]},
    "empty": {"seqnames": {"chr": []}}, "extra": {"seqnames": ["chr1", "chr2", "chrX"], "seqlengths": [100, 200, 50]}, "onlyone": {"seqnames": ["chr1"]},
}
for n, si in SI.items():
    cases.append({"id": f"ctor-seqinfo-{n}", "tags": ["seqinfo", "bad-args"], "inputs": {"s": {"Seqinfo": si}}, "call": {"fn": "identity", "args": ["$s"]}})
    cases.append({"id": f"ctor-gr-seqinfo-{n}", "tags": ["seqinfo", "bad-args"],
                  "inputs": {"g": {"GRanges": {"seqnames": ["chr1", "chr2", "chr1"], "start": [1, 5, 9], "width": [2, 2, 2], "seqinfo": si}}}, "call": {"fn": "identity", "args": ["$g"]}})

out = Path(__file__).parent.parent / "cases" / "grid_construct.yaml"
out.write_text("# GENERATED by gen/grid_construct.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
