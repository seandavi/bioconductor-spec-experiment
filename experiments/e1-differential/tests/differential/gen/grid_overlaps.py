"""Generate cases/grid_overlaps.yaml: findOverlaps over every (query, subject) pair of a pool.

    uv run python tests/differential/gen/grid_overlaps.py

Pool = starts 1..6 x widths 0..3 (includes zero-width). One case per
(type, maxgap, minoverlap) compares all 576 pairs at once.
"""

from __future__ import annotations

from pathlib import Path

import yaml

POOL = [(s, w) for w in range(0, 4) for s in range(1, 7)]
SUBJ = [(10, 2), (3, 4), (3, 4), (5, 0), (1, 8), (2, 1), (3, 5)]


def ir(pairs: list[tuple[int, int]]) -> dict:
    return {"IRanges": {"start": [s for s, _ in pairs], "width": [w for _, w in pairs]}}


pool_ir, subj_ir = ir(POOL), ir(SUBJ)
cases: list[dict] = []
for typ in ("any", "start", "end", "within", "equal"):
    for mg in (-1, 0, 1, 3):
        for mo in (0, 1, 2):
            if typ == "any" and mg >= 0 and mo > 0:
                continue
            cases.append({
                "id": f"grid-fo-{typ}-g{mg}-o{mo}".replace("-g-1", "-gm1"),
                "tags": ["grid", "findOverlaps", typ],
                "inputs": {"q": pool_ir, "s": pool_ir},
                "call": {"fn": "findOverlaps", "args": ["$q", "$s"],
                         "kwargs": {"type": typ, "maxgap": mg, "minoverlap": mo}},
            })
for typ in ("any", "start", "end", "within", "equal"):
    for sel in ("first", "last", "arbitrary"):
        cases.append({
            "id": f"grid-fo-select-{sel}-{typ}",
            "tags": ["grid", "findOverlaps", "select", typ],
            "inputs": {"q": pool_ir, "s": subj_ir},
            "call": {"fn": "findOverlaps", "args": ["$q", "$s"], "kwargs": {"type": typ, "select": sel}},
        })
# fewer queries than subjects: R then walks an NCList built on the query (different hit order)
small_ir = ir(POOL[3:23:5])
for typ in ("any", "start", "end", "within", "equal"):
    for sel in ("all", "first", "last", "arbitrary"):
        kw = {"type": typ} if sel == "all" else {"type": typ, "select": sel}
        cases.append({
            "id": f"grid-fo-qsmall-{sel}-{typ}",
            "tags": ["grid", "findOverlaps", "query-shorter", typ],
            "inputs": {"q": small_ir, "s": pool_ir},
            "call": {"fn": "findOverlaps", "args": ["$q", "$s"], "kwargs": kw},
        })
dup_ir = ir(POOL + POOL[:7])
for typ in ("any", "within", "start", "equal"):
    for drop in ({}, {"drop.self": True}, {"drop.self": True, "drop.redundant": True}, {"drop.redundant": True}):
        tag = "-".join(k.split(".")[1] for k in drop) or "plain"
        cases.append({
            "id": f"grid-fo-self-{typ}-{tag}",
            "tags": ["grid", "findOverlaps", "self", typ],
            "inputs": {"x": dup_ir},
            "call": {"fn": "findOverlaps", "args": ["$x"], "kwargs": {"type": typ, **drop}},
        })
for mg, mo, typ in [(-1, 0, "any"), (2, 0, "within"), (0, 2, "equal")]:
    cases.append({
        "id": f"grid-count-{typ}-g{mg}-o{mo}".replace("-g-1", "-gm1"),
        "tags": ["grid", "countOverlaps", typ],
        "inputs": {"q": pool_ir, "s": subj_ir},
        "call": {"fn": "countOverlaps", "args": ["$q", "$s"], "kwargs": {"type": typ, "maxgap": mg, "minoverlap": mo}},
    })

out = Path(__file__).parent.parent / "cases" / "grid_overlaps.yaml"
out.write_text("# GENERATED by gen/grid_overlaps.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
