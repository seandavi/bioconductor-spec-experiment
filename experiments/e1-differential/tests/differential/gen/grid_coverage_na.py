"""Generate cases/grid_coverage_na.yaml: coverage() with missing weights on random layouts.

    uv run python tests/differential/gen/grid_coverage_na.py

R's engine does not confine an NA weight to the positions its range covers (see the coverage
kernel docstring); these cases pin the layouts where it does and where it does not.
"""

from __future__ import annotations

import random
from pathlib import Path

import yaml

rng = random.Random(8675309)
cases: list[dict] = []


def add(cid: str, tags: list[str], inputs: dict, kwargs: dict) -> None:
    cases.append({"id": cid, "tags": ["coverage", "na", *tags], "inputs": inputs, "call": {"fn": "coverage", "args": ["$x"], "kwargs": kwargs}})


def weights(n: int, typed: str) -> dict:
    ws = [rng.randint(1, 5) for _ in range(n)]
    for i in rng.sample(range(n), rng.randint(1, max(1, n // 2))):
        ws[i] = None  # type: ignore[call-overload]
    return {typed: ws}


k = 0
for layout in ("partition", "partition-offset", "gap", "overlap", "empty-inside", "nested"):
    for _ in range(6):
        n = rng.randint(2, 5)
        if layout.startswith("partition"):
            pos, starts, widths = (1 if layout == "partition" else rng.randint(2, 4)), [], []
            for _ in range(n):
                w = rng.randint(1, 3)
                starts.append(pos), widths.append(w)
                pos += w
        elif layout == "gap":
            pos, starts, widths = 1, [], []
            for _ in range(n):
                w = rng.randint(1, 3)
                starts.append(pos), widths.append(w)
                pos += w + rng.randint(0, 2)
        elif layout == "overlap":
            starts = [rng.randint(1, 8) for _ in range(n)]
            widths = [rng.randint(1, 5) for _ in range(n)]
        elif layout == "empty-inside":
            starts = sorted(rng.randint(1, 10) for _ in range(n))
            widths = [rng.choice([0, 0, 2, 3]) for _ in range(n)]
        else:
            n = min(n, 4)
            starts = [1, 2, 3, 8][:n]
            widths = [10, 5, 1, 2][:n]
        for typed in ("int", "num"):
            x = {"IRanges": {"start": starts, "width": widths}}
            wt = weights(n, typed)
            add(f"covna{k}-{layout}-{typed}", [layout], {"x": x}, {"weight": wt})
            add(f"covna{k}-{layout}-{typed}-width", [layout, "width"], {"x": x}, {"weight": wt, "width": rng.choice([4, 8, 12, max(starts) + max(widths)])})
            add(f"covna{k}-{layout}-{typed}-shift", [layout, "shift"], {"x": x}, {"weight": wt, "shift": rng.choice([-2, 1, 3])})
            g = {"GRanges": {"seqnames": ["a"] * n, "start": starts, "width": widths, "seqinfo": {"seqnames": ["a", "b"], "seqlengths": [rng.choice([None, 12]), 5]}}}
            add(f"covna{k}-{layout}-{typed}-gr", [layout, "gr"], {"x": g}, {"weight": wt})
            g2 = {"GRanges": {"seqnames": [rng.choice(["a", "b"]) for _ in range(n)], "start": starts, "width": widths,
                              "seqinfo": {"seqnames": ["a", "b"], "seqlengths": [rng.choice([None, 12, 30]), rng.choice([None, 6, 20])]}}}
            add(f"covna{k}-{layout}-{typed}-gr2", [layout, "gr"], {"x": g2}, {"weight": wt})
            k += 1

out = Path(__file__).parent.parent / "cases" / "grid_coverage_na.yaml"
out.write_text("# GENERATED by gen/grid_coverage_na.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
