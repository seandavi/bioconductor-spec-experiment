"""Build circular-sequence adversaries and linear/strand controls.

Regeneration preserves reviewed xfail reasons; it never infers acceptance.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

OUT = Path(__file__).parents[1] / "cases" / "redteam_circular.yaml"
cases: list[dict[str, Any]] = []


def gr(start: list[int], width: list[int], strand: str = "+", *, circular: bool | None = True,
       length: int | None = 10, names: list[str] | None = None) -> dict[str, Any]:
    body: dict[str, Any] = {
        "seqnames": ["chrM"], "start": start, "width": width, "strand": strand,
        "seqinfo": {"seqnames": ["chrM"], "seqlengths": [length], "is_circular": [circular]},
    }
    if names is not None:
        body.update(names=names, mcols={"label": names})
    return {"GRanges": body}


def add(cid: str, x: dict[str, Any], y: dict[str, Any] | None, fn: str,
        **kwargs: Any) -> None:
    cases.append({"id": f"rt-circ-{cid}", "tags": ["redteam", "circular", fn],
                  "inputs": {"x": x, **({"y": y} if y is not None else {})},
                  "call": {"fn": fn, "args": ["$x", *(["$y"] if y is not None else [])],
                           "kwargs": kwargs}})


# Origin-spanning ranges: their seqinfo, not an explicit circle.length argument,
# tells R to compare modulo the sequence length.
x, y = gr([9], [4], names=["origin"]), gr([1], [2])
for typ in ("any", "start", "end", "within", "equal"):
    add(f"origin-{typ}", x, y, "findOverlaps", type=typ)
for fn in ("countOverlaps", "overlapsAny", "subsetByOverlaps", "nearest", "precede", "follow", "distance"):
    add(f"origin-{fn}", x, y, fn)
add("nearest-choice", x, gr([1, 8], [2, 1]), "nearest")
add("nearest-all", x, gr([1, 8], [2, 1]), "nearest", select="all")
add("nearest-origin-adjacent", gr([10], [1]), gr([1, 5], [1, 1]), "nearest")
add("origin-invert", x, y, "subsetByOverlaps", invert=True)
add("origin-minoverlap", x, y, "findOverlaps", minoverlap=2)
add("origin-opposite", x, gr([1], [2], "-"), "findOverlaps")
add("origin-ignore-strand", x, gr([1], [2], "-"), "findOverlaps", **{"ignore.strand": True})
add("origin-linear-control", gr([9], [4], circular=False), gr([1], [2], circular=False), "findOverlaps")
add("origin-unknown-control", gr([9], [4], circular=None), gr([1], [2], circular=None), "findOverlaps")
add("origin-unknown-length", gr([9], [4], length=None), gr([1], [2], length=None), "findOverlaps")
add("shift-equal", gr([21], [2]), y, "findOverlaps", type="equal")
add("shift-start", gr([-9], [2]), y, "findOverlaps", type="start")
add("shift-within", gr([11], [1]), y, "findOverlaps", type="within")
add("zero-interior", gr([12], [0]), y, "findOverlaps")
add("zero-boundary", gr([11], [0]), y, "findOverlaps")
add("multi-turn", gr([8], [26]), gr([4], [1]), "findOverlaps")
add("self-drops", gr([1, 11], [2, 2]), None, "findOverlaps", **{"drop.self": True})
add("self-redundant", gr([1, 11], [2, 2]), None, "findOverlaps", **{"drop.self": True, "drop.redundant": True})
add("origin-coverage", x, None, "coverage")
add("origin-trim", x, None, "trim")
add("origin-reduce", x, None, "reduce", **{"with.revmap": True})

old = yaml.safe_load(OUT.read_text()) if OUT.exists() else {}
reasons = {c["id"]: c["xfail"] for c in old.get("cases", []) if "xfail" in c}
for case in cases:
    if case["id"] in reasons:
        case["xfail"] = reasons[case["id"]]
OUT.write_text("# Generated by gen/redteam_circular.py; reviewed xfail reasons are retained.\n" +
               yaml.safe_dump({"cases": cases}, sort_keys=False, width=110))
print(f"wrote {len(cases)} cases")
