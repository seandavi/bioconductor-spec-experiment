"""Generate cases/grid_coverage.yaml: random coverage() calls (shift / width / weight, circular sequences).

    uv run python tests/differential/gen/grid_coverage.py
"""

from __future__ import annotations

import random
from pathlib import Path

import yaml

rng = random.Random(5150)
cases: list[dict] = []
SI_PLAIN = {"seqnames": ["a", "b", "c"], "seqlengths": [40, None, 15]}
SI_CIRC = {"seqnames": ["a", "b", "c"], "seqlengths": [40, 25, 15], "is_circular": [False, True, True]}
for k in range(12):
    n = rng.choice([5, 12, 25])
    ir = {"IRanges": {"start": [rng.randint(-5, 45) for _ in range(n)], "width": [rng.choice([0, 1, 3, 8, 20, 50]) for _ in range(n)]}}
    kw: dict = {}
    if rng.random() < 0.6:
        kw["shift"] = [rng.randint(-10, 10) for _ in range(rng.choice([1, n]))]
    if rng.random() < 0.5:
        kw["weight"] = [rng.randint(-2, 4) for _ in range(rng.choice([1, n]))]
    if rng.random() < 0.4:
        kw["width"] = rng.randint(0, 60)
    cases.append({"id": f"cov{k}-ir", "tags": ["coverage", "random"], "inputs": {"x": ir}, "call": {"fn": "coverage", "args": ["$x"], **({"kwargs": kw} if kw else {})}})
    for sname, si in (("plain", SI_PLAIN), ("circ", SI_CIRC)):
        g = {"GRanges": {"seqnames": [rng.choice(["a", "b", "c"]) for _ in range(n)], "start": ir["IRanges"]["start"], "width": ir["IRanges"]["width"],
                         "strand": [rng.choice(["+", "-", "*"]) for _ in range(n)], "seqinfo": si}}
        gkw = dict(kw)
        if "width" in gkw and rng.random() < 0.7:
            gkw["width"] = [rng.randint(0, min(15, 60)) for _ in range(3)]
        cases.append({"id": f"cov{k}-gr-{sname}", "tags": ["coverage", "random"], "inputs": {"x": g}, "call": {"fn": "coverage", "args": ["$x"], **({"kwargs": gkw} if gkw else {})}})

out = Path(__file__).parent.parent / "cases" / "grid_coverage.yaml"
out.write_text("# GENERATED by gen/grid_coverage.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
