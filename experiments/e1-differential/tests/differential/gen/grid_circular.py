"""Generate cases/grid_circular.yaml: overlaps on circular sequences (periodic coordinates).

    uv run python tests/differential/gen/grid_circular.py

Random ranges (starts outside 1..L, multi-turn widths, empties) on one circular sequence of known
length, one of unknown length and one linear, through every overlap-family operation.
"""

from __future__ import annotations

import random
from pathlib import Path

import yaml

rng = random.Random(1234567)
SI = {"seqnames": ["circ", "unk", "lin"], "seqlengths": [10, None, 25], "is_circular": [True, True, False]}
cases: list[dict] = []


def gr(n: int, wide: bool = False, lo: int = -12) -> dict:
    return {"GRanges": {
        "seqnames": [rng.choice(["circ", "circ", "circ", "unk", "lin"]) for _ in range(n)],
        "start": [rng.randint(lo, 30) for _ in range(n)],
        "width": [rng.choice([0, 1, 2, 3, 5, 9, 10, 14, 26] if wide else [0, 1, 2, 3, 5, 8]) for _ in range(n)],
        "strand": [rng.choice(["+", "-", "*"]) for _ in range(n)], "seqinfo": SI}}


def add(cid: str, inputs: dict, fn: str, kwargs: dict | None = None, args: list | None = None) -> None:
    call: dict = {"fn": fn, "args": args or list(f"${k}" for k in inputs)}
    if kwargs:
        call["kwargs"] = kwargs
    cases.append({"id": cid, "tags": ["circular", fn], "inputs": inputs, "call": call})


for tag, (nq, ns, wide) in {"short": (4, 14, False), "equal": (10, 10, False), "long": (16, 5, False), "wide": (6, 6, True)}.items():
    for rep in range(6):
        q, s = gr(nq, wide), gr(ns, wide)
        inp = {"q": q, "s": s}
        for typ in ("any", "start", "end", "within", "equal"):
            kw: dict = {"type": typ}
            if typ == "any" and rng.random() < 0.4:  # maxgap on start/end/equal/within is engine-dependent in R (ADR-0007)
                kw["maxgap"] = rng.choice([0, 2])
            if rng.random() < 0.3 and typ != "any" and "maxgap" not in kw:
                kw["minoverlap"] = rng.choice([1, 2])
            add(f"circ-{tag}{rep}-fo-{typ}", inp, "findOverlaps", kw)
        for sel in ("first", "last", "arbitrary"):
            add(f"circ-{tag}{rep}-fo-{sel}", inp, "findOverlaps", {"select": sel})
        add(f"circ-{tag}{rep}-fo-ignstrand", inp, "findOverlaps", {"ignore.strand": True, "minoverlap": 2})
        add(f"circ-{tag}{rep}-count", inp, "countOverlaps")
        add(f"circ-{tag}{rep}-any", inp, "overlapsAny", {"type": "within"})
        add(f"circ-{tag}{rep}-subset", inp, "subsetByOverlaps")
        add(f"circ-{tag}{rep}-self", {"q": q}, "findOverlaps", {"drop.self": True, "drop.redundant": rng.random() < 0.5})
        add(f"circ-{tag}{rep}-self-all", {"q": q}, "findOverlaps")
        # nearest-family ops get positive coordinates: negative ones hit R's sentinel quirk (ADR-0008)
        pinp = {"q": gr(nq, wide, lo=2), "s": gr(ns, wide, lo=2)}
        for fn, sels in (("nearest", ("arbitrary", "all")), ("precede", ("first",)), ("follow", ("last",))):
            for sel in sels:
                add(f"circ-{tag}{rep}-{fn}-{sel}", pinp, fn, {"select": sel})

out = Path(__file__).parent.parent / "cases" / "grid_circular.yaml"
out.write_text("# GENERATED by gen/grid_circular.py - edit the generator, not this file.\n" + yaml.safe_dump({"cases": cases}, default_flow_style=None, width=200))
print(f"wrote {out} ({len(cases)} cases)")
