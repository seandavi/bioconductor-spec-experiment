"""Build conformance/REPORT.md from reports/r.json + reports/python.json.

    uv run python -m ranges_e2.conformance.report
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from .runner import CONFORMANCE_DIR, load_xfail


def build(base: Path = CONFORMANCE_DIR) -> str:
    r_report = json.loads((base / "reports" / "r.json").read_text())["cases"]
    py_report = json.loads((base / "reports" / "python.json").read_text())["cases"]
    xfail = load_xfail(base)
    groups: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    statements: dict[tuple[str, str], str] = {}
    for path in sorted((base / "cases").glob("*.json")):
        doc = json.loads(path.read_text())
        for cid, text in doc["clauses"].items():
            statements[(doc["group"], cid)] = text
            groups[doc["group"]].setdefault(cid, [])
        for c in doc["cases"]:
            groups[doc["group"]][c["clause"]].append(c["id"])

    def count(report: dict[str, str], ids: list[str], status: str) -> int:
        return sum(report.get(i) == status for i in ids)

    lines = [
        "# Conformance report",
        "",
        "Generated by `python -m ranges_e2.conformance.report`; do not edit.",
        "R = `Rscript conformance/r/run.R check` (drift detector). Python = `python -m ranges_e2.conformance.runner`.",
        "",
        "## Summary",
        "",
        "| Group | Cases | Clauses | R pass | Py pass | Py xfail | Py fail |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    totals = [0] * 6
    for group, clauses in groups.items():
        ids = [i for v in clauses.values() for i in v]
        row = [
            len(ids),
            len(clauses),
            count(r_report, ids, "pass"),
            count(py_report, ids, "pass"),
            count(py_report, ids, "xfail"),
            sum(py_report.get(i) in ("fail", "error", "xpass") for i in ids),
        ]
        totals = [a + b for a, b in zip(totals, row)]
        lines.append(f"| {group} | " + " | ".join(map(str, row)) + " |")
    lines.append("| **total** | " + " | ".join(f"**{t}**" for t in totals) + " |")
    lines += ["", "## Clauses", ""]
    for group, clauses in groups.items():
        lines += [f"### {group}", "", "| Clause | Cases | R | Py | Statement |", "|---|---:|---:|---:|---|"]
        for cid, ids in clauses.items():
            py = f"{count(py_report, ids, 'pass')}" + (
                f" (+{count(py_report, ids, 'xfail')} xfail)" if count(py_report, ids, "xfail") else ""
            )
            lines.append(
                f"| `{cid}` | {len(ids)} | {count(r_report, ids, 'pass')} | {py} | {statements[(group, cid)]} |"
            )
        lines.append("")
    lines += ["## Cases ranges_e2 does not pass (xfail.json)", "", "| Case | Reason |", "|---|---|"]
    lines += [f"| `{cid}` | {why} |" for cid, why in xfail.items()]
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    out = CONFORMANCE_DIR / "REPORT.md"
    out.write_text(build())
    print(f"wrote {out}")
