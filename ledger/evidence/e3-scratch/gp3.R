suppressWarnings(suppressMessages(library(GenomicRanges)))
al <- function(l,h) cat(l, ":", paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" "), "\n")
SI <- Seqinfo(c("b","a","c"), c(40, NA, 30), c(FALSE, NA, FALSE))
x <- GRanges(c("c","a","c","b"), IRanges(c(8,2,9,22), c(10,4,9,22)), strand=c("*","+","-","+"), seqinfo=SI)
y <- GRanges(c("c","c","a"), IRanges(c(19,1,30), c(24,0,30)), strand=c("-","*","-"), seqinfo=SI)
al("full", follow(x,y,select="all"))
al("only c x0", follow(x[1],y,select="all"))
al("only c x0, y c only", follow(x[1],y[1:2],select="all"))
y2 <- GRanges(c("c","c"), IRanges(c(19,1), c(24,0)), strand=c("-","*"), seqinfo=SI); al("y2 with SI", follow(x[1],y2,select="all"))
y3 <- GRanges(c("c","c"), IRanges(c(19,1), c(24,0)), strand=c("-","*")); al("y3 no SI", follow(GRanges("c:8-10:*"),y3,select="all"))
y4 <- GRanges(c("c","c"), IRanges(c(19,1), c(24,1)), strand=c("-","*"), seqinfo=SI); al("y4 [1,1]", follow(x[1],y4,select="all"))
y5 <- GRanges(c("c","c"), IRanges(c(19,1), c(24,0)), strand=c("-","*"), seqinfo=Seqinfo("c")); al("y5 SI c only no length", follow(x[1]  ,y5,select="all"))
y6 <- GRanges(c("c","c"), IRanges(c(19,1), c(24,0)), strand=c("-","*"), seqinfo=Seqinfo("c",30)); al("y6 SI c len30", follow(GRanges("c:8-10:*",seqinfo=Seqinfo("c",30)),y6,select="all"))
