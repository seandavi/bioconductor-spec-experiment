source("spec/scratch/h.R")
z <- function(l, v) cat(l, ":", paste(ifelse(is.na(v),"NA",v-1L), collapse=","), "\n")
S <- IRanges(c(1,5,10,20,20),c(3,7,12,25,22)); p("S",S)  # idx 0..4
Q <- IRanges(c(4,8,13,0,15,26,6,10,21,5),c(4,9,14,0,15,30,6,10,21,4)); p("Q",Q)
z("nearest first", nearest(Q,S))
z("nearest arb", nearest(Q,S,select="arbitrary"))
h <- nearest(Q,S,select="all"); cat("all:", paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" "), "\n")
z("precede", precede(Q,S))
h <- precede(Q,S,select="all"); cat("p all:", paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" "), "\n")
z("follow", follow(Q,S))
h <- follow(Q,S,select="all"); cat("f all:", paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" "), "\n")
cat("--self\n")
z("nearest self", nearest(S)); z("precede self", precede(S)); z("follow self", follow(S))
cat("--tie\n")
T <- IRanges(c(1,9),c(3,12)); Qt <- IRanges(5,5); z("tie first", nearest(Qt,T))
h <- nearest(Qt,T,select="all"); cat("tie all:", paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" "), "\n")
T2 <- IRanges(c(1,6),c(3,12)); z("tie2", nearest(IRanges(4,5),T2)); 
cat("--overlap preferred\n")
z("ovl", nearest(IRanges(2,11), IRanges(c(1,3,5,12),c(1,4,20,13))))
h <- nearest(IRanges(2,11), IRanges(c(1,3,5,12),c(1,4,20,13)), select="all"); cat("ovl all:", paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" "), "\n")
cat("--zero width\n")
z("zq nearest", nearest(IRanges(c(5,1),c(4,0)), IRanges(c(1,8),c(3,9))))
z("zs nearest", nearest(IRanges(c(5)), IRanges(c(1,6,3),c(3,5,2))))
z("zq precede", precede(IRanges(c(5,4,6),c(4,3,5)), IRanges(c(1,5,6,8),c(3,7,9,9))))
z("zq follow", follow(IRanges(c(5,4,6),c(4,3,5)), IRanges(c(1,5,6,8),c(3,7,9,9))))
cat("--precede details\n")
z("p1", precede(IRanges(1,3), IRanges(c(4,5,3,4),c(6,6,6,9))))
h <- precede(IRanges(1,3), IRanges(c(4,5,3,4),c(6,6,6,9)),select="all"); cat("p1 all:", paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" "), "\n")
z("p2 start==end+1", precede(IRanges(1,3), IRanges(4,6)))
z("p2 overlap", precede(IRanges(1,3), IRanges(3,6)))
z("f1", follow(IRanges(10,12), IRanges(c(1,3,7,8),c(3,5,9,9))))
h <- follow(IRanges(10,12), IRanges(c(1,3,7,8),c(3,5,9,9)),select="all"); cat("f1 all:", paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" "), "\n")
z("f1 adj", follow(IRanges(10,12), IRanges(c(8,2),c(9,10))))
z("f nested", follow(IRanges(10,12), IRanges(c(1),c(30))))
z("empty subj", nearest(IRanges(1,3), IRanges())); z("empty q", nearest(IRanges(), IRanges(1,3)))
