m1 <- GRanges("a", IRanges(1,2)); mcols(m1)$x <- 1; m2 <- GRanges("a", IRanges(1,2)); mcols(m2)$y <- "q"; r <- try(c(m1,m2)); if(!inherits(r,"try-error")) print(mcols(r))
