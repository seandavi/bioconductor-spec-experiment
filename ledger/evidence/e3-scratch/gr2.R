source("spec/scratch/h.R")
g_s <- function(x) paste(sprintf("%s:%d-%d:%s", as.character(seqnames(x)), start(x), end(x), as.character(strand(x))), collapse=" ")
gp <- function(l,x) cat(l,":", g_s(x), "\n")
v <- function(l,v) cat(l,":",paste(v,collapse=","),"\n")
g <- GRanges(c("chr2","chr1","chr10","chr1"), IRanges(c(5,1,3,2),width=c(2,3,1,0)), strand=c("+","-","*","+"))
gp("g",g); v("seqlevels", seqlevels(g)); v("seqlevels class", class(seqnames(g))); v("sl", seqlengths(g)); v("circ", isCircular(g)); v("genome", genome(g))
g2 <- GRanges(c("chr2","chr1"), IRanges(1:2,3:4)); v("strand default", as.character(strand(g2)))
g3 <- GRanges(c("b","a","b"), IRanges(1:3,3:5), seqinfo=Seqinfo(c("b","a","c"), c(100,200,NA), c(FALSE,TRUE,NA), c("g1","g1",NA)))
gp("g3",g3); v("sl", seqlevels(g3)); v("len", seqlengths(g3)); v("circ", isCircular(g3)); v("genome", genome(g3))
cat("--sort\n")
gs <- GRanges(c("b","a","b","c","a","b","a"), IRanges(c(5,1,3,1,1,3,1),width=c(2,2,2,2,2,1,2)), strand=c("+","-","-","*","+","+","+"), seqinfo=Seqinfo(c("b","a","c")))
gp("gs", gs); v("order", order(gs)-1L); gp("sort", sort(gs)); v("order dec", order(gs,decreasing=TRUE)-1L)
v("rank", rank(gs,ties.method="first")); v("dup", duplicated(gs)); 
gp("unique", unique(gs))
cat("--sort order: strand vs start\n")
gt <- GRanges("a", IRanges(c(1,1,1,5),c(2,2,2,6)), strand=c("*","-","+","+")); v("strand ord", order(gt)-1L)
gt <- GRanges("a", IRanges(c(2,1,1,5),c(2,2,3,6)), strand=c("+","+","+","+")); v("end ord", order(gt)-1L)
cat("--concat\n")
a <- GRanges("chr2:1-2:+"); b <- GRanges("chr3:1-2:-"); gp("c", c(a,b)); v("sl", seqlevels(c(a,b))); v("sl rev", seqlevels(c(b,a)))
c1 <- GRanges("a", IRanges(1,2), seqinfo=Seqinfo(c("a","b"), c(10,20))); c2 <- GRanges("c", IRanges(1,2), seqinfo=Seqinfo(c("c","a"), c(30,NA))); cc <- c(c1,c2); v("sl", seqlevels(cc)); v("len", seqlengths(cc))
c3 <- GRanges("a", IRanges(1,2), seqinfo=Seqinfo(c("a"), c(11))); r <- try(c(c1,c3)); 
