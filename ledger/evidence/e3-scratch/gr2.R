c6 <- GRanges("a", IRanges(1,2), seqinfo=Seqinfo(c("a"), NA, NA, "hg38")); r <- try(c(c5,c6)); v("genome conflict", class(r))
c7 <- GRanges("a", IRanges(1,2), seqinfo=Seqinfo(c("a"), NA, FALSE)); r <- try(c(c4,c7)); v("circ conflict2", class(r))
c8 <- GRanges("a", IRanges(1,2), seqinfo=Seqinfo(c("a"), NA, NA)); r <- try(c(c4,c8)); v("circ NA merge", isCircular(r))
r <- try(c(c5,c8)); v("genome NA merge", genome(r))
v("len merge NA", seqlengths(c(c1, GRanges("b",IRanges(1,2),seqinfo=Seqinfo(c("b"),NA)))))
