suppressWarnings(source("spec/scratch/h.R"))
g_s <- function(x) paste(sprintf("%s:%d-%d:%s", as.character(seqnames(x)), start(x), end(x), as.character(strand(x))), collapse=" ")
gp <- function(l,x) cat(l,":", g_s(x), "\n")
v <- function(l,v) cat(l,":",paste(v,collapse=","),"\n")
sw <- function(e) suppressWarnings(e)
G <- GRanges(c("a","a","a","b"), IRanges(c(10,10,10,5),width=c(5,5,5,3)), strand=c("+","-","*","-"), seqinfo=Seqinfo(c("a","b"), c(100,50)))
gp("G",G)
gp("shift", shift(G,2))
gp("narrow", narrow(G, start=2, width=2))
gp("narrow end", narrow(G, end=3))
gp("resize 2 start", resize(G,2)); gp("resize 2 end", resize(G,2,fix="end")); gp("resize 2 center", resize(G,2,fix="center")); 
gp("resize 8 center", resize(G,8,fix="center"));
gp("flank 3", flank(G,3)); gp("flank 3 start=F", flank(G,3,start=FALSE)); gp("flank -3", flank(G,-3)); gp("flank both", flank(G,3,both=TRUE)); gp("flank both F", flank(G,3,start=FALSE,both=TRUE));
gp("flank ignore", flank(G,3,ignore.strand=TRUE))
gp("prom", promoters(G, 4, 2)); gp("prom def", promoters(G))
gp("resize ign", resize(G,2,ignore.strand=TRUE))
cat("--out of bounds creation and trim\n")
t <- sw(GRanges(c("a","a","a"), IRanges(c(12,-5,-5),c(15,-3,200)), seqinfo=Seqinfo("a", 10))); gp("t", t); gp("trim", trim(t))
t0 <- sw(GRanges("a", IRanges(c(1,11),c(0,10)), seqinfo=Seqinfo("a", 10))); gp("t0", t0); gp("trim0", trim(t0))
t1 <- sw(GRanges("a", IRanges(c(12),c(11)), seqinfo=Seqinfo("a", 10))); gp("t1", t1); gp("trim1", trim(t1))
cat("--reduce\n")
R <- GRanges(c("b","a","a","a","a","b"), IRanges(c(1,5,7,5,6,2),c(3,6,9,6,8,6)), strand=c("+","+","+","-","*","+"), seqinfo=Seqinfo(c("b","a","c"), c(20,30,40))); gp("R",R)
gp("reduce", reduce(R)); gp("reduce ign", reduce(R, ignore.strand=TRUE)); gp("reduce mg", reduce(R, min.gapwidth=2))
r <- reduce(R, with.revmap=TRUE); v("revmap", sapply(mcols(r)$revmap, function(z) paste(z-1L,collapse="/")))
r <- reduce(R, with.revmap=TRUE, ignore.strand=TRUE); v("revmap ign", sapply(mcols(r)$revmap, function(z) paste(z-1L,collapse="/"))); gp("r ign", r)
gp("reduce drop", reduce(GRanges(c("a","a"),IRanges(c(5,1),c(4,3)),strand="+"), drop.empty.ranges=TRUE))
cat("--range\n")
gp("range", range(R)); gp("range ign", range(R, ignore.strand=TRUE))
cat("--gaps\n")
gp("gaps", gaps(R)); gp("gaps ign", gaps(R, ignore.strand=TRUE))
gp("gaps noinfo", gaps(GRanges(c("a","a"), IRanges(c(5,20),c(10,25)), strand="+")))
gp("gaps start end", gaps(R, start=1, end=10))
cat("--disjoin\n")
gp("disjoin", disjoin(R)); gp("disjoin ign", disjoin(R, ignore.strand=TRUE))
cat("--setops\n")
A <- GRanges(c("a","a","b"), IRanges(c(1,10,1),c(8,20,5)), strand=c("+","-","+"), seqinfo=Seqinfo(c("a","b"))); B <- GRanges(c("a","a","b"), IRanges(c(5,10,3),c(12,15,9)), strand=c("+","*","-"), seqinfo=Seqinfo(c("a","b")))
gp("A",A); gp("B",B)
gp("union", union(A,B)); gp("intersect", intersect(A,B)); gp("setdiff", setdiff(A,B))
gp("union ign", union(A,B,ignore.strand=TRUE)); gp("intersect ign", intersect(A,B,ignore.strand=TRUE)); gp("setdiff ign", setdiff(A,B,ignore.strand=TRUE))
gp("punion", sw(punion(A[1],B[1]))); gp("pintersect", pintersect(A[1],B[1]));  gp("psetdiff", psetdiff(A[1],B[1]))
gp("pint *", pintersect(A[1],B[2])); 
gp("pint -+", try(pintersect(A[2],B[1])))
