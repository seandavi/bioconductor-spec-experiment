suppressWarnings(suppressMessages(library(GenomicRanges)))
g_s <- function(x) paste(sprintf("%s:%d-%d:%s", as.character(seqnames(x)), start(x), end(x), as.character(strand(x))), collapse=" ")
gp <- function(l,x) cat(l,":", g_s(x), "\n")
q <- function(l, e) { r <- try(e, silent=TRUE); if (inherits(r,"try-error")) cat(l,": ERROR\n") else gp(l, r) }
si <- Seqinfo(c("n","c","u"), c(30,30,NA), c(FALSE,TRUE,NA))
x <- suppressWarnings(GRanges(c("n","n","c","u"), IRanges(c(25,-3,25,25),c(35,2,35,35)), strand="+", seqinfo=si))
gp("x", x)
gp("reduce", reduce(x)); gp("setdiff x empty", setdiff(x, x[0])); gp("union", union(x, x[0])); gp("intersect", intersect(x,x))
gp("disjoin", disjoin(x)); gp("range", range(x)); gp("gaps", gaps(x))
cv <- coverage(x); for (n in names(cv)) cat(n, ":", paste0(runLength(cv[[n]]),"x",runValue(cv[[n]]),collapse=" "), "\n")
q("pint disjoint same strand", pintersect(GRanges("a:1-3:+"), GRanges("a:7-9:+")))
q("pint disjoint same strand", pintersect(GRanges("a:1-3:+"), GRanges("a:7-9:+"), resolve.empty="start.x"))
q("pint disjoint same strand", pintersect(GRanges("a:1-3:+"), GRanges("a:7-9:+"), resolve.empty="max.start"))
q("punion gap", punion(GRanges("a:1-3:+"), GRanges("a:7-9:+")))
q("punion gap fill", punion(GRanges("a:1-3:+"), GRanges("a:7-9:+"), fill.gap=TRUE))
q("psetdiff split", psetdiff(GRanges("a:1-10:+"), GRanges("a:4-5:+")))
q("pint adj", pintersect(GRanges("a:1-3:+"), GRanges("a:4-9:+")))
print(args(getMethod("pintersect", c("GRanges","GRanges"))))
