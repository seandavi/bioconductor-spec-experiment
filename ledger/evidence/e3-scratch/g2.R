source("spec/scratch/h.R")
fo <- function(l, q, s, ...) { h <- findOverlaps(q, s, ...); cat(l, ":", if (length(h)) paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" ") else "-", "\n") }
S <- IRanges(c(1,5,5,10,3),c(10,4,6,12,3))   # [1,10] [5,4] [5,6] [10,12] [3,3]
p("S", S)
Q <- IRanges(c(5,5,4,11,0,13,3,1), c(4,6,5,11,0,14,2,10)) # [5,4] [5,6] [4,5] [11,11] [0,0] [13,14] [3,2] [1,10]
p("Q", Q)
for (t in c("any","start","end","within","equal")) fo(t, Q, S, type=t)
cat("--maxgap\n")
for (mg in c(0,1,2)) fo(paste("any mg",mg), Q, S, maxgap=mg)
for (mg in c(0,1)) fo(paste("start mg",mg), Q, S, type="start", maxgap=mg)
for (mg in c(0,1)) fo(paste("end mg",mg), Q, S, type="end", maxgap=mg)
for (mg in c(0,1)) fo(paste("within mg",mg), Q, S, type="within", maxgap=mg)
cat("--minoverlap\n")
for (mo in c(0,1,2,3)) fo(paste("any mo",mo), Q, S, minoverlap=mo)
cat("--select\n")
for (sel in c("first","last","arbitrary")) { h <- findOverlaps(Q,S,select=sel); p(sel, h-1L)}
h <- findOverlaps(Q,S,select="all"); print(class(h)); print(c(length(queryHits(h)), nLnode(h), nRnode(h)))
p("count", countOverlaps(Q,S)); p("any", as.integer(overlapsAny(Q,S))); 
p("count mo", countOverlaps(Q,S,minoverlap=2)); 
p("count start", countOverlaps(Q,S,type="start")); 
p("sbo", subsetByOverlaps(Q,S))
p("sbo inv", subsetByOverlaps(Q,S,invert=TRUE))
cat("--pair-order\n")
h <- findOverlaps(IRanges(c(1,1,20),c(30,30,30)), IRanges(c(25,1,5,2),c(26,2,6,3)))
cat(paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" "), "\n")
h <- findOverlaps(IRanges(c(1,1),c(30,30)), IRanges(c(1),c(2)), select="arbitrary"); print(h)
cat("--equal/start/end non-zero\n")
fo("start", IRanges(5,8), IRanges(c(5,5,6,3),c(8,9,8,8)), type="start")
fo("end", IRanges(5,8), IRanges(c(5,5,6,3),c(8,9,8,8)), type="end")
fo("within", IRanges(5,8), IRanges(c(5,5,6,3),c(8,9,8,8)), type="within")
fo("equal", IRanges(5,8), IRanges(c(5,5,6,3),c(8,9,8,8)), type="equal")
fo("start mg1", IRanges(5,8), IRanges(c(5,6,7,3),c(8,9,8,8)), type="start", maxgap=1)
fo("end mg1", IRanges(5,8), IRanges(c(5,6,7,3),c(8,9,7,8)), type="end", maxgap=1)
fo("any mg", IRanges(5,8), IRanges(c(1,2,10,11),c(3,4,12,12)), maxgap=0)
fo("any mg1", IRanges(5,8), IRanges(c(1,2,10,11),c(3,4,12,12)), maxgap=1)
fo("any mg2", IRanges(5,8), IRanges(c(1,2,10,11),c(3,4,12,13)), maxgap=2)
fo("within mg", IRanges(5,8), IRanges(c(4,3,2,5),c(9,10,10,8)), type="within", maxgap=1)
fo("within mg0", IRanges(5,8), IRanges(c(4,3,2,5),c(9,10,10,8)), type="within", maxgap=0)
fo("within mg1", IRanges(5,8), IRanges(c(4,3,2,5),c(9,10,10,8)), type="within", maxgap=1)
fo("within mg2", IRanges(5,8), IRanges(c(4,3,2,5),c(9,10,10,8)), type="within", maxgap=2)
fo("mo", IRanges(5,8), IRanges(c(1,4,6,8,9),c(5,5,7,12,12)), minoverlap=2)
fo("mo", IRanges(5,8), IRanges(c(1,4,6,8,9),c(5,5,7,12,12)), minoverlap=1)
fo("mo 4", IRanges(5,8), IRanges(c(5,1),c(8,12)), minoverlap=4)
fo("mo 5", IRanges(5,8), IRanges(c(5,1),c(8,12)), minoverlap=5)
fo("mo within", IRanges(5,8), IRanges(c(5,1,4),c(8,12,12)), minoverlap=4, type="within")
