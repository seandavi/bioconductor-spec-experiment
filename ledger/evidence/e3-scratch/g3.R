fo <- function(l, q, s, ...) { h <- try(findOverlaps(q, s, ...),silent=TRUE); if(inherits(h,"try-error")) {cat(l,": ERROR\n");return()}; cat(l, ":", if (length(h)) paste(sprintf("%d-%d", queryHits(h)-1L, subjectHits(h)-1L), collapse=" ") else "-", "\n") }
Qr <- IRanges(5,8)
Sj <- IRanges(c(5,5,6,1,4,3),c(8,9,8,20,8,9))  # equal, end+1, start+1, big, start-1, 2/1
for (mg in c(-1,0,1,2,3)) fo(paste("within mg",mg), Qr, Sj, type="within", maxgap=mg)
for (mg in c(-1,0,1)) fo(paste("start mg",mg), Qr, Sj, type="start", maxgap=mg)
for (mg in c(-1,0,1)) fo(paste("end mg",mg), Qr, Sj, type="end", maxgap=mg)
for (mg in c(-1,0,1,2)) fo(paste("equal mg",mg), Qr, Sj, type="equal", maxgap=mg)
for (mo in c(0,1,4,5)) fo(paste("start mo",mo), Qr, Sj, type="start", minoverlap=mo)
for (mo in c(0,4,5)) fo(paste("equal mo",mo), Qr, Sj, type="equal", minoverlap=mo)
fo("start mo5 on disjoint start", IRanges(5,8), IRanges(5,6), type="start", minoverlap=3)
fo("start mo adjacent", IRanges(5,8), IRanges(c(5,9),c(4,12)), type="start", minoverlap=1)
fo("any mo>mg", IRanges(5,8), IRanges(c(1,7),c(5,20)), minoverlap=2)
fo("any mg -1 mo 2", IRanges(5,8), IRanges(c(1,7),c(5,20)), minoverlap=2, maxgap=-1)
fo("any mg 0 mo 0", IRanges(5,8), IRanges(c(1,9),c(5,20)), minoverlap=0, maxgap=0)
fo("any mg 0 mo 1", IRanges(5,8), IRanges(c(1,9),c(5,20)), minoverlap=1, maxgap=0)
fo("equal zero", IRanges(5,4), IRanges(c(5,4),c(4,3)), type="equal")
fo("equal zero mg1", IRanges(5,4), IRanges(c(5,4,6),c(4,3,5)), type="equal",maxgap=1)
fo("within zero", IRanges(5,4), IRanges(c(5,4),c(4,3)), type="within")
fo("within zero 2", IRanges(5,4), IRanges(c(4,5,3),c(5,6,8)), type="within")
fo("within mo", IRanges(5,4), IRanges(c(4,5,3),c(5,6,8)), type="within", minoverlap=1)
fo("within mo q", IRanges(5,6), IRanges(c(4,5,3),c(5,6,8)), type="within", minoverlap=3)
fo("any mo zero q", IRanges(5,4), IRanges(c(1),c(8)), minoverlap=1)
fo("start empty", IRanges(), IRanges(1,3)); fo("start empty2", IRanges(1,3), IRanges())
